// vhost is the rendered form of a site that both servers understand.
type vhost struct {
	Name    string
	Domain  string
	DocRoot string
	PHP     string
}

type webConfig struct {
	Port       int
	LocalRoot  string // served for localhost: the PAMPP start page
	Logs       string
	Tmp        string
	DefaultPHP string
	PHPs       []string // branches with running pools
	Workers    int
	Hosts      []vhost

	// HTTPS is served on SSLPort with one certificate covering every site.
	SSL      bool
	SSLPort  int
	CertFile string
	KeyFile  string
}

// ---------------- nginx ----------------

func writeNginxConfig(p Paths, nginxDir string, c webConfig) (string, error) {
	var b strings.Builder
	fmt.Fprintf(&b, `# Generated by PAMPP - edits will be overwritten
worker_processes 1;
error_log "%s/nginx-error.log" warn;
pid "%s/nginx.pid";

events { worker_connections 1024; }

http {
    include       "%s/conf/mime.types";
    default_type  application/octet-stream;
    sendfile      off;
    keepalive_timeout 65;
    client_max_body_size 512m;
    server_names_hash_bucket_size 128;
    access_log "%s/nginx-access.log";
    gzip on;

`, fwd(c.Logs), fwd(c.Tmp), fwd(nginxDir), fwd(c.Logs))

	if c.SSL {
		fmt.Fprintf(&b, `    ssl_certificate     "%s";
    ssl_certificate_key "%s";
    ssl_protocols TLSv1.2 TLSv1.3;
    http2 on;

`, fwd(c.CertFile), fwd(c.KeyFile))
	}

	for _, br := range c.PHPs {
		fmt.Fprintf(&b, "    upstream %s {\n", phpUpstream(br))
		for i := 0; i < c.Workers; i++ {
			fmt.Fprintf(&b, "        server 127.0.0.1:%d;\n", phpPort(br, i))
		}
		b.WriteString("    }\n")
	}

	writeServer := func(names, root, php string, def bool) {
		suffix := ""
		if def {
			suffix = " default_server"
		}
		listen := fmt.Sprintf("listen %d%s;", c.Port, suffix)
		if c.SSL {
			listen += fmt.Sprintf("\n        listen %d ssl%s;", c.SSLPort, suffix)
		}
		fmt.Fprintf(&b, `
    server {
        %s
        server_name %s;
        root "%s";
        index index.php index.html index.htm;
        charset utf-8;
        autoindex on;

        location / {
            try_files $uri $uri/ /index.php?$query_string;
        }
        location ~ /\.(?!well-known) { deny all; }
`, listen, names, fwd(root))
		if php != "" {
			fmt.Fprintf(&b, `        location ~ [^/]\.php(/|$) {
            fastcgi_split_path_info ^(.+?\.php)(/.*)$;
            if (!-f $document_root$fastcgi_script_name) { return 404; }
            fastcgi_pass %s;
            fastcgi_index index.php;
            include "%s/conf/fastcgi_params";
            fastcgi_param SCRIPT_FILENAME $document_root$fastcgi_script_name;
            fastcgi_param PATH_INFO $fastcgi_path_info;
            fastcgi_read_timeout 300;
            fastcgi_buffers 16 32k;
            fastcgi_buffer_size 64k;
        }
`, phpUpstream(php), fwd(nginxDir))
		}
		b.WriteString("    }\n")
	}

	writeServer("localhost 127.0.0.1", c.LocalRoot, c.DefaultPHP, true)
	for _, h := range c.Hosts {
		writeServer(h.Domain+" *."+h.Domain, h.DocRoot, h.PHP, false)
	}
	b.WriteString("}\n")

	conf := p.Etc("nginx", "nginx.conf")
	return conf, os.WriteFile(conf, []byte(b.String()), 0o644)
}

// ---------------- Apache ----------------

var apacheModules = []string{
	"mod_actions", "mod_alias", "mod_allowmethods", "mod_auth_basic", "mod_authn_core", "mod_authn_file",
	"mod_authz_core", "mod_authz_groupfile", "mod_authz_host", "mod_authz_user", "mod_autoindex",
	"mod_deflate", "mod_dir", "mod_env", "mod_expires", "mod_filter", "mod_headers", "mod_include",
	"mod_isapi", "mod_lbmethod_byrequests", "mod_log_config", "mod_mime", "mod_negotiation",
	"mod_proxy", "mod_proxy_balancer", "mod_proxy_fcgi", "mod_rewrite", "mod_setenvif",
	"mod_slotmem_shm", "mod_socache_shmcb", "mod_ssl", "mod_version",
}

func writeApacheConfig(p Paths, apacheDir string, c webConfig) (string, error) {
	var b strings.Builder
	fmt.Fprintf(&b, `# Generated by PAMPP - edits will be overwritten
Define SRVROOT "%s"
ServerRoot "${SRVROOT}"
Listen %d
ServerName localhost:%d
PidFile "%s/httpd.pid"

`, fwd(apacheDir), c.Port, c.Port, fwd(c.Tmp))
	for _, m := range apacheModules {
		name := strings.TrimPrefix(m, "mod_")
		if exists(filepath.Join(apacheDir, "modules", m+".so")) {
			fmt.Fprintf(&b, "LoadModule %s_module modules/%s.so\n", name, m)
		}
	}
	fmt.Fprintf(&b, `
ErrorLog "%s/apache-error.log"
LogLevel warn
LogFormat "%%h %%l %%u %%t \"%%r\" %%>s %%b" common
CustomLog "%s/apache-access.log" common
TypesConfig conf/mime.types
AddDefaultCharset UTF-8
DirectoryIndex index.php index.html index.htm
EnableSendfile off
AcceptFilter http none
AcceptFilter https none
ProxyFCGIBackendType GENERIC
# php-cgi (unlike php-fpm) needs a plain filesystem path in SCRIPT_FILENAME.
ProxyFCGISetEnvIf "true" SCRIPT_FILENAME "%%{reqenv:DOCUMENT_ROOT}%%{reqenv:SCRIPT_NAME}"
Timeout 300

<Directory />
    AllowOverride none
    Require all denied
</Directory>
<Files ".ht*">
    Require all denied
</Files>

`, fwd(c.Logs), fwd(c.Logs))

	if c.SSL {
		fmt.Fprintf(&b, `Listen %d
SSLCertificateFile "%s"
SSLCertificateKeyFile "%s"
SSLProtocol all -SSLv3 -TLSv1 -TLSv1.1
SSLSessionCache "shmcb:%s/ssl_scache(512000)"

`, c.SSLPort, fwd(c.CertFile), fwd(c.KeyFile), fwd(c.Tmp))
	}

	for _, br := range c.PHPs {
		fmt.Fprintf(&b, "<Proxy balancer://%s>\n", phpUpstream(br))
		for i := 0; i < c.Workers; i++ {
			fmt.Fprintf(&b, "    BalancerMember fcgi://127.0.0.1:%d\n", phpPort(br, i))
		}
		b.WriteString("    ProxySet timeout=300\n</Proxy>\n")
	}

	writeHost := func(name, aliases, root, php string) {
		writeVHost(&b, c, false, name, aliases, root, php)
		if c.SSL {
			writeVHost(&b, c, true, name, aliases, root, php)
		}
	}

	writeHost("localhost", "127.0.0.1", c.LocalRoot, c.DefaultPHP)
	for _, h := range c.Hosts {
		writeHost(h.Domain, "*."+h.Domain, h.DocRoot, h.PHP)
	}

	conf := p.Etc("apache", "httpd.conf")
	return conf, os.WriteFile(conf, []byte(b.String()), 0o644)
}

func writeVHost(b *strings.Builder, c webConfig, ssl bool, name, aliases, root, php string) {
	port := c.Port
	if ssl {
		port = c.SSLPort
	}
	fmt.Fprintf(b, "\n<VirtualHost *:%d>\n    ServerName %s\n", port, name)
	if ssl {
		b.WriteString("    SSLEngine on\n")
	}
	if aliases != "" {
		fmt.Fprintf(b, "    ServerAlias %s\n", aliases)
	}
	fmt.Fprintf(b, `    DocumentRoot "%s"
    <Directory "%s">
        Options Indexes FollowSymLinks
        AllowOverride All
        Require all granted
    </Directory>
`, fwd(root), fwd(root))
	if php != "" {
		fmt.Fprintf(b, `    <FilesMatch "\.php$">
        SetHandler "proxy:balancer://%s/"
    </FilesMatch>
`, phpUpstream(php))
	}
	b.WriteString("</VirtualHost>\n")
}

// ---------------- process control ----------------

type webServer struct {
	kind string // nginx | apache
	dir  string
	conf string
	port int // HTTP port, used to wait until the server actually listens
	proc *process
}

func (w *webServer) exe() string {
	if w.kind == "apache" {
		return filepath.Join(w.dir, "bin", "httpd.exe")
	}
	return filepath.Join(w.dir, "nginx.exe")
}

func (w *webServer) test() error {
	var cmd = hiddenCmd(w.exe(), "-t", "-f", w.conf)
	if w.kind == "nginx" {
		cmd = hiddenCmd(w.exe(), "-t", "-p", fwd(w.dir)+"/", "-c", fwd(w.conf))
	}
	cmd.Dir = w.dir
	out, err := cmd.CombinedOutput()
	if err != nil {
		return fmt.Errorf("yapılandırma hatası: %s", strings.TrimSpace(string(out)))
	}
	return nil
}

func (w *webServer) start(logPath string) error {
	if w.kind == "nginx" {
		os.MkdirAll(filepath.Join(w.dir, "logs"), 0o755)
		os.MkdirAll(filepath.Join(w.dir, "temp"), 0o755)
	}
	if err := w.test(); err != nil {
		return err
	}
	var cmd = hiddenCmd(w.exe(), "-f", w.conf, "-d", w.dir)
	if w.kind == "nginx" {
		cmd = hiddenCmd(w.exe(), "-p", fwd(w.dir)+"/", "-c", fwd(w.conf))
	}
	cmd.Dir = w.dir
	proc, err := startProcess(cmd, logPath)
	if err != nil {
		return err
	}
	w.proc = proc
	if proc.wait(800 * time.Millisecond) {
		return fmt.Errorf("%s hemen kapandı, logs klasörüne bakın", w.kind)
	}
	// Apache only listens once its child process is up (slower with SSL).
	if w.port > 0 && !waitPort(w.port, 15*time.Second) {
		w.stop()
		return fmt.Errorf("%s port %d üzerinde dinlemeye başlamadı, logs klasörüne bakın", w.kind, w.port)
	}
	return nil
}

// reload applies a new config. nginx reloads in place; Apache is restarted.
func (w *webServer) reload(logPath string) error {
	if err := w.test(); err != nil {
		return err
	}
	if w.kind == "nginx" && w.proc.alive() {
		cmd := hiddenCmd(w.exe(), "-p", fwd(w.dir)+"/", "-c", fwd(w.conf), "-s", "reload")
		cmd.Dir = w.dir
		if err := cmd.Run(); err == nil {
			// Old workers keep accepting briefly while the new ones spin up.
			time.Sleep(600 * time.Millisecond)
			return nil
		}
	}
	w.stop()
	return w.start(logPath)
}

func (w *webServer) stop() {
	if !w.proc.alive() {
		return
	}
	if w.kind == "nginx" {
		cmd := hiddenCmd(w.exe(), "-p", fwd(w.dir)+"/", "-c", fwd(w.conf), "-s", "stop")
		cmd.Dir = w.dir
		_ = cmd.Run()
		if w.proc.wait(3 * time.Second) {
			return
		}
	}
	w.proc.kill()
}

func sortedBranches(set map[string]bool) []string {
	var out []string
	for k := range set {
		out = append(out, k)
	}
	sort.Slice(out, func(i, j int) bool { return compareVersions(out[i], out[j]) > 0 })
	return out
}
