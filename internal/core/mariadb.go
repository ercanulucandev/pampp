package core

import (
	"fmt"
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"time"
)

type mariaDB struct {
	dir     string // bin/mariadb
	dataDir string
	conf    string
	port    int
	proc    *process
}

func (m *mariaDB) binary(names ...string) string {
	for _, n := range names {
		if p := filepath.Join(m.dir, "bin", n); exists(p) {
			return p
		}
	}
	return ""
}

func (m *mariaDB) writeConfig(logs string) error {
	conf := fmt.Sprintf(`# Generated by PAMPP - edits will be overwritten
[mysqld]
basedir="%s"
datadir="%s"
port=%d
bind-address=127.0.0.1
character-set-server=utf8mb4
collation-server=utf8mb4_unicode_ci
max_allowed_packet=256M
innodb_buffer_pool_size=256M
log-error="%s/mariadb-error.log"
skip-name-resolve

[client]
port=%d
default-character-set=utf8mb4
`, fwd(m.dir), fwd(m.dataDir), m.port, fwd(logs), m.port)
	return os.WriteFile(m.conf, []byte(conf), 0o644)
}

// initialize creates the system tables on first start (root without password).
func (m *mariaDB) initialize(logPath string) error {
	if exists(filepath.Join(m.dataDir, "mysql")) {
		return nil
	}
	installer := m.binary("mariadb-install-db.exe", "mysql_install_db.exe")
	if installer == "" {
		return fmt.Errorf("mariadb-install-db.exe bulunamadı")
	}
	os.RemoveAll(m.dataDir)
	cmd := hiddenCmd(installer, "--datadir="+m.dataDir, "--port="+strconv.Itoa(m.port))
	cmd.Dir = m.dir
	out, err := cmd.CombinedOutput()
	_ = os.WriteFile(logPath, out, 0o644)
	if err != nil {
		return fmt.Errorf("veritabanı ilk kurulumu başarısız: %s", lastLine(string(out)))
	}
	return nil
}

func (m *mariaDB) start(logPath string) error {
	server := m.binary("mariadbd.exe", "mysqld.exe")
	if server == "" {
		return fmt.Errorf("MariaDB kurulu değil")
	}
	if !portFree(m.port) {
		return portBusyError(m.port)
	}
	if err := m.initialize(logPath); err != nil {
		return err
	}
	cmd := hiddenCmd(server, "--defaults-file="+m.conf, "--console")
	cmd.Dir = m.dir
	proc, err := startProcess(cmd, logPath)
	if err != nil {
		return err
	}
	m.proc = proc
	if !waitPort(m.port, 20*time.Second) {
		proc.kill()
		return fmt.Errorf("MariaDB başlatılamadı, logs/mariadb-error.log dosyasına bakın")
	}
	return nil
}

func (m *mariaDB) stop() {
	if !m.proc.alive() {
		return
	}
	if admin := m.binary("mariadb-admin.exe", "mysqladmin.exe"); admin != "" {
		cmd := hiddenCmd(admin, "-uroot", "--host=127.0.0.1", "--port="+strconv.Itoa(m.port), "shutdown")
		_ = cmd.Run()
		if m.proc.wait(15 * time.Second) {
			return
		}
	}
	m.proc.kill()
}

func lastLine(s string) string {
	lines := strings.Split(strings.TrimSpace(s), "\n")
	return strings.TrimSpace(lines[len(lines)-1])
}
